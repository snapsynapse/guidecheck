if __name__ == "__main__":
    import sys

    source = Path(__file__).resolve().parents[1] / "profiles" / "3.0.0" / "shape-registry.json"
    if sys.argv[1:] == ["--write"]:
        text = Path(__file__).read_text(encoding="ascii")
        head, _, tail = text.partition("REGISTRY_BYTES = (\n")
        body = "".join(f"    {line!r}\n" for line in source.read_bytes().splitlines(keepends=True))
        Path(__file__).write_text(head + "REGISTRY_BYTES = (\n" + body + ")\n" + tail.partition(")\n")[2], encoding="ascii")
    raise SystemExit(0 if REGISTRY_BYTES == source.read_bytes() else 1)
